/**
 * Render production FolderFlow macOS brand assets from vector sources:
 * 1. Renders assets/icon-source.svg -> temp 1024x1024 transparent PNG -> `tauri icon` -> src-tauri/icons/*
 * 2. Renders assets/dmg-background.png (660x400) matching tauri.conf.json bundle.macOS.dmg layout.
 *
 * Uses Playwright Chromium (already in devDependencies — zero extra packages).
 */
import { execFileSync } from "node:child_process";
import { mkdtempSync, readdirSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { chromium } from "@playwright/test";

const root = resolve(fileURLToPath(new URL("..", import.meta.url)));
const svgPath = join(root, "assets/icon-source.svg");
const dmgBgPath = join(root, "assets/dmg-background.png");
const iconsDir = join(root, "src-tauri/icons");

const KEEP_ICONS = new Set([
  "32x32.png",
  "64x64.png",
  "128x128.png",
  "128x128@2x.png",
  "icon.png",
  "icon.icns",
]);

