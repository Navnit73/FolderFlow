async function main() {
  const workDir = mkdtempSync(join(tmpdir(), "ff-brand-"));
  const iconPng1024 = join(workDir, "icon-1024.png");
  const svgMarkup = readFileSync(svgPath, "utf8");

  const browser = await chromium.launch({ headless: true });
  try {
    // 1. Render 1024x1024 transparent icon master
    const iconPage = await browser.newPage({
      viewport: { width: 1024, height: 1024 },
      deviceScaleFactor: 1,
    });
    await iconPage.setContent(
      `<!doctype html><html><body style="margin:0;background:transparent;width:1024px;height:1024px;overflow:hidden">${svgMarkup}</body></html>`,
    );
    await iconPage.screenshot({ path: iconPng1024, omitBackground: true });
    await iconPage.close();

    // 2. Render 660x400 DMG installer background
    const dmgPage = await browser.newPage({
      viewport: { width: 660, height: 400 },
      deviceScaleFactor: 1,
    });
    await dmgPage.setContent(dmgHtml);
    await dmgPage.screenshot({ path: dmgBgPath });
    await dmgPage.close();
  } finally {
    await browser.close();
  }

  // 3. Generate macOS iconset + PNGs via Tauri CLI
  execFileSync("pnpm", ["exec", "tauri", "icon", iconPng1024, "-o", iconsDir], {
    cwd: root,
    stdio: "inherit",
  });

  // Remove non-macOS platform icons & directories generated by `tauri icon`
  for (const entry of readdirSync(iconsDir)) {
    if (!KEEP_ICONS.has(entry)) {
      rmSync(join(iconsDir, entry), { recursive: true, force: true });
    }
  }

  rmSync(workDir, { recursive: true, force: true });
  console.log("Generated macOS icons in src-tauri/icons and assets/dmg-background.png");
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
